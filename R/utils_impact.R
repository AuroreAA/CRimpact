#' Bias of Pearson's correlation coefficient under contamination
#'
#' Compute the bias of Pearson's correlation functional at a contaminated
#' distribution
#' \eqn{F_\varepsilon = (1 - \varepsilon) F + \varepsilon H}{F_epsilon =
#' (1 - epsilon) F + epsilon H}, where \eqn{F} is the model
#' distribution, \eqn{H} is the contamination distribution, and
#' \eqn{\varepsilon \in [0, 0.5)}{epsilon} is the contamination fraction.
#'
#' @param model  list of relevant quantities detailing the distribution of
#' ordinal measurement scales, as generated by [get_model()] or
#' [simple_model()].
#' @param epsilon  vector of contamination fractions. Its elements must be
#' between 0 and 0.5.
#' @param contamination  the type of contamination. Possible values are:
#' - `"careless"`: contamination distribution corresponding to (stylized)
#'   careless responding behavior, as generated by [careless()].
#' - `"reversed"`: contamination distribution corresponding to respondents
#'   reversing one or both scales in a model distribution, as generated by
#'   [reversed()].
#' - `"adversarial"`: adversarial contamination distribution resulting in
#'   maximum upward or downward bias, as generated by [adversarial()].
#' @param \dots additional arguments to be passed to the corresponding function
#' generating the relevant quantities of the contamination distribution.
#'
#' @return A list with the following components:
#' \item{epsilon}{vector of contamination fractions.}
#' \item{rho}{true correlation coefficient at the model distribution.}
#' \item{rho_contaminated}{vector containing the correlation coefficient at the
#' contaminated distribution for each contamination fraction.}
#' \item{bias}{vector containing the bias of the correlation at the
#' contaminated distribution for each contamination fraction.}
#'
#' @author Andreas Alfons and Max Welz
#'
#' @references
#' M. Welz, A. Archimbaud, A. Alfons (2026). Quantifying the impact of careless
#' responding. PsyArXiv. \doi{10.31234/osf.io/8fj6p_v2}.
#'
#' @seealso
#' [get_model()], [simple_model()]
#'
#' [careless()], [reversed()], [adversarial()]
#'
#' @examples
#' # generate model distribution
#' model_XY <- simple_model(prob = "centered", K = 9,
#'                          length = 5, rho_w = 0.4,
#'                          rho = -0.4)
#'
#' # contamination fractions
#' eps <- c(0, 0.1, 0.2, 0.3, 0.4, 0.49)
#'
#' # straightlining from extreme response categories
#' bias(model_XY, epsilon = eps, contamination = "careless",
#'      type = "straightlining", target = "extreme")
#'
#'
#' # straightlining from all response categories
#' bias(model_XY, epsilon = eps, contamination = "careless",
#'      type = "straightlining", target = "all")
#'
#' # random responding from extreme response categories
#' bias(model_XY, epsilon = eps, contamination = "careless",
#'      type = "random", target = "extreme")
#'
#' # random responding from all response categories
#' bias(model_XY, epsilon = eps, contamination = "careless",
#'      type = "random", target = "all")
#'
#' @export

bias <- function(model, epsilon, contamination = "careless", ...) {

  # extract components from object for model distribution
  mu_X <- model$X$mean
  Sigma_X <- model$X$cov
  mu_Y <- model$Y$mean
  Sigma_Y <- model$Y$cov
  Sigma_XY <- model$cov_XY

  # if necessary, initialize object for contamination distribution
  if (is.character(contamination)) {
    contamination <- match.arg(
      contamination,
      choices = c("careless", "reversed", "adversarial")
    )
    if (contamination == "careless") contamination <- careless(model, ...)
    else if (contamination == "reversed") contamination <- reversed(model, ...)
    else contamination <- adversarial(model, ...)
  }

  # extract components of object for contamination distribution
  nu_X <- contamination$X$mean
  Psi_X <- contamination$X$cov
  nu_Y <- contamination$Y$mean
  Psi_Y <- contamination$Y$cov
  Psi_XY <- contamination$cov_XY

  # extract weight vectors
  a <- model$a
  b <- model$b

  # extract variances and covariance at model distribution F
  var_F_U <- model$U$var
  var_F_V <- model$V$var
  cov_F_UV <- model$cov_UV

  # calculate variances and covariance at contamination distribution H
  var_H_U <- drop(crossprod(a, Psi_X) %*% a)
  var_H_V <- drop(crossprod(b, Psi_Y) %*% b)
  cov_H_UV <- drop(crossprod(a, Psi_XY) %*% b)

  # calculate difference of means at distributions F and H
  diff_E_U <- model$U$mean - drop(crossprod(a, nu_X))
  diff_E_V <- model$V$mean - drop(crossprod(b, nu_Y))

  # calculate covariance and variances at contaminated distribution G
  var_G_U <- (1 - epsilon) * var_F_U + epsilon * var_H_U +
    epsilon * (1 - epsilon) * diff_E_U^2
  var_G_V <- (1 - epsilon) * var_F_V + epsilon * var_H_V +
    epsilon * (1 - epsilon) * diff_E_V^2
  cov_G_UV <- (1 - epsilon) * cov_F_UV + epsilon * cov_H_UV +
    epsilon * (1 - epsilon) * diff_E_U * diff_E_V

  # calculate correlation coefficient at contaminated distribution G
  rho_G <- cov_G_UV / (sqrt(var_G_U) * sqrt(var_G_V))

  # return results
  list(epsilon = epsilon, rho = model$rho, rho_contaminated = rho_G,
       bias = rho_G - model$rho)

}



#' Visualize bias or correlation curves at specific contaminating distribution
#'
#'
#' @param bias bias of Pearson's correlation functional at a contaminated
#' distribution
#' @param digits number of digits shown in the hover.
#' @param type either `"Correlation"` or  `"Bias"`: the different type of impact
#' to plot
#'
#' @return A \code{ggplot} object
#'
#' @importFrom scales percent
#'
#' @author Aurore Archimbaud
#' @noRd
#'
#' @rawNamespace import(ggplot2, except = last_plot)
bias_plot <- function (bias, digits = 2, type = c("Correlation", "Bias"))
{
  # initializations
  type <- match.arg(type)
  eps <- bias$epsilon
  rho <- bias$rho

  if(type == "Correlation"){
    BS <- bias$rho_contaminated
  }else{
    BS <- bias$bias
  }

  if(!is.null(digits)){
    BS <- round(BS, digits)
  }

  gg <- ggplot(data = data.frame(bias = BS, contamination = eps),
               aes(y = bias, x = contamination, text = paste0(
                 "Contamination: ", scales::percent(contamination, accuracy = 1),
                 "<br>",
                 type, ": ", bias
               ),  group = 1)) +
    geom_line() +
    scale_x_continuous(labels = scales::percent)+
    xlab("Contamination fraction") + ylab(type)



  if(type == "Correlation"){
    gg <- gg +
      geom_line(data = data.frame(x = eps, y = rho),
                mapping = aes(x = eps, y = rho,
                              text = paste0(
                                "True correlation: ",
                                rep(rho, length(eps))
                              ), group = 1),
                linetype = "dashed", color = "lightcoral") +
      ylim(-1, 1)
  }
  if(type == "Bias"){
    y_breakdown <- seq(-(1+rho), 1-rho, 0.02)
    gg <- gg +
      ylim(-(1+rho), 1-rho)
  }
  return(gg)
}


#' Maximum bias of Pearson's correlation coefficient under contamination
#'
#' Compute the maximum upward and downward bias of Pearson's correlation
#' functional at a contaminated distribution
#' \eqn{F_\varepsilon = (1 - \varepsilon) F + \varepsilon H}{F_epsilon =
#' (1 - epsilon) F + epsilon H}, where \eqn{F} is the model
#' distribution, \eqn{H} is the contamination distribution, and
#' \eqn{\varepsilon \in [0, 0.5)}{epsilon} is the contamination fraction.
#'
#' @param model  list of relevant quantities detailing the distribution of
#' ordinal measurement scales, as generated by [get_model()] or
#' [simple_model()].
#' @param epsilon  vector of contamination fractions. Its elements must be
#' between 0 and 0.5.
#'
#' @return A list with the following components:
#' \item{epsilon}{vector of contamination fractions.}
#' \item{rho}{true correlation coefficient at the model distribution.}
#' \item{rho_upward}{vector containing (for each contamination fraction) the
#' correlation coefficient at the contamination distribution resulting in
#' the maximum upward bias.}
#' \item{bias_upward}{vector containing the maximum upward bias of the
#' correlation at the contaminated distribution for each contamination
#' fraction.}
#' \item{rho_downward}{vector containing (for each contamination fraction) the
#' correlation coefficient at the contamination distribution resulting in
#' the maximum downward bias.}
#' \item{bias_downward}{vector containing the maximum downward bias of the
#' correlation at the contaminated distribution for each contamination
#' fraction.}
#'
#' @author Andreas Alfons and Max Welz
#'
#' @references
#' M. Welz, A. Archimbaud, A. Alfons (2026). Quantifying the impact of careless
#' responding. PsyArXiv. \doi{10.31234/osf.io/8fj6p_v2}.
#'
#' @seealso
#' [get_model()], [simple_model()]
#'
#' [adversarial()]
#'
#' @examples
#' # generate model distribution
#' model_XY <- simple_model(prob = "centered", K = 9,
#'                          length = 5, rho_w = 0.4,
#'                          rho = -0.4)
#'
#' # contamination fractions
#' eps <- c(0, 0.1, 0.2, 0.3, 0.4, 0.49)
#'
#' # maximum upward and downward bias
#' max_bias(model_XY, epsilon = eps)
#'
#' # note that these are equivalent to:
#' bias(model_XY, epsilon = eps, contamination = "adversarial",
#'      direction = "upward")
#' bias(model_XY, epsilon = eps, contamination = "adversarial",
#'      direction = "downward")
#'
#' @export

max_bias <- function(model, epsilon) {

  # extract relevant quantities at model distribution F
  E_F_U <- model$U$mean
  E_F_V <- model$V$mean
  var_F_U <- model$U$var
  var_F_V <- model$V$var
  cov_F_UV <- model$cov_UV

  # bounds of support
  M_U <- model$U$M
  M_V <- model$V$M

  # collect quantities that only depend on model distribution F
  m_F_U <- (1 - epsilon) * var_F_U + epsilon * (1 - epsilon) * E_F_U^2
  m_F_V <- (1 - epsilon) * var_F_V + epsilon * (1 - epsilon) * E_F_V^2
  m_F_UV <- (1 - epsilon) * cov_F_UV + epsilon * (1 - epsilon) * E_F_U * E_F_V

  # calculate relevant quantities for maximum upward and downward bias
  rho_upward <- (m_F_UV + epsilon * M_U * M_V) /
    (sqrt(m_F_U + epsilon * M_U^2) * sqrt(m_F_V + epsilon * M_V^2))
  rho_downward <- (m_F_UV - epsilon * M_U * M_V) /
    (sqrt(m_F_U + epsilon * M_U^2) * sqrt(m_F_V + epsilon * M_V^2))

  # return results
  list(epsilon = epsilon, rho = model$rho, rho_upward = rho_upward,
       bias_upward = rho_upward - model$rho, rho_downward = rho_downward,
       bias_downward = rho_downward - model$rho)

}



#' Compute the breakdown value of Pearson's correlation coefficient.
#'
#' Consider a correlation functional at a contaminated distribution
#' \eqn{F_\varepsilon = (1 - \varepsilon) F + \varepsilon H}{F_epsilon =
#' (1 - epsilon) F + epsilon H}, where \eqn{F} is the model
#' distribution, \eqn{H} is the contamination distribution, and
#' \eqn{\varepsilon \in [0, 0.5)}{epsilon} is the contamination fraction.
#' The breakdown value is defined as the smallest contamination fraction so
#' that the correlation functional at the contaminated distribution flips its
#' sign compared to the true correlation at the model distribution.
#'
#' @param model  list of relevant quantities detailing the distribution of
#' ordinal measurement scales, as generated by [get_model()], [simple_model()],
#' or [identical_model()].
#'
#' @return The breakdown value.
#'
#' @note A stricter definition of the breakdown value of correlation
#' functionals is common in the statistical literature. It defines the
#' breakdown value as the smallest contamination fraction so that the
#' correlation functional at the contaminated distribution is negative
#' for two random variables with correlation 1 at the model distribution.
#'
#' @author Andreas Alfons and Max Welz
#'
#' @references
#' M. Welz, A. Archimbaud, A. Alfons (2026). Quantifying the impact of careless
#' responding. PsyArXiv. \doi{10.31234/osf.io/8fj6p_v2}.
#'
#' @seealso [get_model()], [simple_model()], [identical_model()]
#'
#' @examples
#' # generate model distribution
#' model_XY <- simple_model(prob = "centered", K = 9,
#'                          length = 5, rho_w = 0.4,
#'                          rho = -0.4)
#'
#' # compute breakdown value
#' breakdown(model_XY)
#'
#' # verification with maximum bias
#' max_bias(model_XY, epsilon = breakdown(model_XY))
#'
#' @export

breakdown <- function(model) {

  # extract relevant quantities at model distribution F
  E_F_U <- model$U$mean
  E_F_V <- model$V$mean
  var_F_U <- model$U$var
  var_F_V <- model$V$var
  cov_F_UV <- model$cov_UV

  # # check if the model distribution F is valid for breakdown value calcuations
  # # (true correlation of 1)
  # # Update: Actually, we define the breakdown value more generally.
  # rho_F <- cov_F_UV / (sqrt(var_F_U) * sqrt(var_F_V))
  # if (rho_F < 1 - sqrt(.Machine$double.eps)) {
  #   stop("Invalid model distribution for breakdown value calculation.\nThe ",
  #        "true correlation of the scores must be 1 (here it is ", rho_F,").")
  # }

  # bounds of support
  M_U <- model$U$M
  M_V <- model$V$M

  # useful products
  prod_E_F <- E_F_U * E_F_U
  prod_M <- M_U * M_V

  # calculate breakdown value
  if (cov_F_UV > 0) {
    # Below, we use the expressions from Theorem 3 of the paper, which assumes
    # a nonnegative true correlation. Essentially, we use the expression of the
    # correlation pushed downwards under adversarial contamination to solve for
    # the breakdown value.
    tmp <- prod_E_F - cov_F_UV - prod_M
    sqrt <- sqrt(tmp^2 + 4 * prod_E_F * cov_F_UV)
    if (prod_E_F > 0) {
      (tmp + sqrt) / (2 * prod_E_F)
    } else if (prod_E_F < 0) {
      (tmp - sqrt) / (2 * prod_E_F)
    } else {
      cov_F_UV / (cov_F_UV + prod_M)
    }
  } else if (cov_F_UV < 0) {
    # If the true correlation is negative, we obtain similar expressions using
    # the correlation pushed upwards under adversarial contamination to solve
    # for the breakdown value.
    tmp <- prod_E_F - cov_F_UV + prod_M
    sqrt <- sqrt(tmp^2 + 4 * prod_E_F * cov_F_UV)
    if (prod_E_F > 0) {
      (tmp - sqrt) / (2 * prod_E_F)
    } else if (prod_E_F < 0) {
      (tmp + sqrt) / (2 * prod_E_F)
    } else {
      cov_F_UV / (cov_F_UV - prod_M)
    }
  } else 0

}


#' Visualize maximal bias or correlation curves at specific contaminating distribution
#'
#' @param maxbias Maximum bias of Pearson's correlation coefficient under contamination
#' @param digits number of digits shown in the hover.
#' @param type either `"Correlation"` or  `"Bias"`: the different type of impact
#' to plot
#' @param direction either `"Upward"`, `"Downward"` or `"Maximum"`
#' @param breakdown breakdown value of Pearson's correlation coefficient for a
#'  correlation functional at a contaminated distribution
#'
#' @noRd
#'
#' @author Aurore Archimbaud
max_bias_plot <- function(maxbias, digits = 2,
                              type = c("Correlation", "Bias"),
                              direction = c("Upward", "Downward", "Maximum"),
                              breakdown){

  # initializations
  type <- match.arg(type)
  direction <- match.arg(direction)
  eps <- maxbias$epsilon
  rho <- maxbias$rho
  # B <- numeric()
  # txt <- character()
  type_name <- ifelse(type == "Correlation", "rho", "bias")
  direction <- ifelse(direction == "Maximum", ifelse(rho < 0, "Upward", "Downward"),
                      direction)

  direction <- tolower(direction)
  B <- maxbias[[paste(type_name, direction, sep = "_")]]
  txt <- paste("Maximum", direction,  tolower(type))

  if(!is.null(digits)){
    B <- round(B, digits)
  }

  gg <- ggplot(data = data.frame(maxbias = B, contamination = eps),
               mapping = aes(y = maxbias, x = contamination,
                             text = paste0(
                               "Contamination: ", scales::percent(contamination, accuracy = 1),
                               "<br>",
                               type, ": ",  maxbias
                             ),  group = 1)) +
    geom_line() +
    scale_x_continuous(labels = scales::percent) +
    xlab("Contamination fraction") + ylab(txt)

  if(type == "Correlation"){
    gg <- gg +
      geom_line(data = data.frame(x = eps, y = rho),
                mapping = aes(x = eps, y = rho,
                              text = paste0(
                                "True correlation: ",
                                rep(rho,
                                    length(eps))
                              ), group = 1),
                linetype = "dashed", color = "lightcoral") +

      ylim(-1, 1)
  }
  if(type == "Bias"){
    y_breakdown <- seq(-(1+rho), 1-rho, 0.02)
    gg <- gg +
      geom_line(data = data.frame(x = breakdown, y = y_breakdown),
                mapping = aes(x = x, y = y_breakdown,
                              text = paste0(
                                "Breakdown value: ",
                                rep(scales::percent(breakdown, accuracy = 0.1),
                                    length(y_breakdown))
                              ), group = 1),
                linetype = "dashed", color = "lightcoral")

  }
  return(gg)
}



## bound for maximum upward or downward bias
#' @export

bias_bound <- function(model, epsilon, direction = NULL) {

  # initializations
  rho <- model$rho
  if (is.null(direction)) {
    # by default, take the larger of upward or downward bias
    direction <- if (rho < 0) "upward" else "downward"
  } else direction <- match.arg(direction, choices = c("upward", "downward"))

  # select function to be optimized according to direction of bias
  if (direction == "upward") {
    rho_contaminated <- rho_contaminated_upward
    control_list <- list(fnscale = -1)  # maximize
  } else {
    rho_contaminated <- rho_contaminated_downward
    control_list <- list()  # minimize
  }

  # numerical optimization given a weighted mixture of two point-mass
  # distributions in respective corner points
  opt_list <- lapply(epsilon, function(eps) {
    if (eps == 0) list(par = NA_real_, value = rho)
    else {
      optim(0.5, rho_contaminated, model = model, epsilon = eps,
            method = "L-BFGS-B", lower = 0, upper = 1,
            control = control_list)
    }
  })

  # extract values of optimal weight and corresponding contaminated correlation
  w <- sapply(opt_list, "[[", "par")
  rho_G <- sapply(opt_list, "[[", "value")

  # return results
  list(epsilon = epsilon, rho = model$rho, rho_contaminated = rho_G,
       bias = rho_G - model$rho, direction = direction, w = w)

}


## utility functions for numerical optimization
## Note: The optimization needs to be done for each contamination fraction,
##       hence 'epsilon' needs to be a scalar here.

# correlation pushed upward under contaminated distribution
rho_contaminated_upward <- function(w, model, epsilon) {

  # extract relevant quantities at model distribution F
  E_F_U <- model$U$mean
  E_F_V <- model$V$mean
  var_F_U <- model$U$var
  var_F_V <- model$V$var
  cov_F_UV <- model$cov_UV

  # bounds of support
  M_U <- model$U$M
  M_V <- model$V$M

  # compute covariance and variance under contaminated distribution G
  # TODO: If necessary, we can define some constants to avoid unnecessary
  #       recomputation. But for now, I prioritized readability of the code.
  var_G_U <- (1 - epsilon) * var_F_U + 4 * epsilon * w * (1 - w) * M_U^2 +
    epsilon * (1 - epsilon) * (E_F_U + (1 - 2 * w) * M_U)^2
  var_G_V <- (1 - epsilon) * var_F_V + 4 * epsilon * w * (1 - w) * M_V^2 +
    epsilon * (1 - epsilon) * (E_F_V + (1 - 2 * w) * M_V)^2
  cov_G_UV <- (1-epsilon) * cov_F_UV + 4 * epsilon * w * (1-w) * M_U * M_V +
    epsilon * (1-epsilon) * (E_F_U + (1-2*w) * M_U) * (E_F_V + (1-2*w) * M_V)

  # return correlation under contaminated distribution G
  cov_G_UV / sqrt(var_G_U * var_G_V)

}

# correlation pushed downward under contaminated distribution
rho_contaminated_downward <- function(w, model, epsilon) {

  # extract relevant quantities at model distribution F
  E_F_U <- model$U$mean
  E_F_V <- model$V$mean
  var_F_U <- model$U$var
  var_F_V <- model$V$var
  cov_F_UV <- model$cov_UV

  # bounds of support
  M_U <- model$U$M
  M_V <- model$V$M

  # compute covariance and variance under contaminated distribution G
  # TODO: If necessary, we can define some constants to avoid unnecessary
  #       recomputation. But for now, I prioritized readability of the code.
  var_G_U <- (1 - epsilon) * var_F_U + 4 * epsilon * w * (1 - w) * M_U^2 +
    epsilon * (1 - epsilon) * (E_F_U + (1 - 2 * w) * M_U)^2
  var_G_V <- (1 - epsilon) * var_F_V + 4 * epsilon * w * (1 - w) * M_V^2 +
    epsilon * (1 - epsilon) * (E_F_V - (1 - 2 * w) * M_V)^2
  cov_G_UV <- (1-epsilon) * cov_F_UV - 4 * epsilon * w * (1-w) * M_U * M_V +
    epsilon * (1-epsilon) * (E_F_U + (1-2*w) * M_U) * (E_F_V - (1-2*w) * M_V)

  # return correlation under contaminated distribution G
  cov_G_UV / sqrt(var_G_U * var_G_V)

}
