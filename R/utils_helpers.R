#' Void internal function to check a supplied PMF
#'
#' A supplied probability mass function (PMF) must be a numeric vector with nonnegative elements that sum up to 1.
#'
#' @param x PMF of a rating-scale variable
#' @author Max Welz
#' @noRd
.input_check_pmf <- function(x)
{
  if(!is.vector(x)) stop("Probability mass functions must be a vector")
  if(!is.numeric(x)) stop("Probability mass functions must be numeric")
  if(!all(x >= 0.0)) stop("All elements in probability mass functions must be nonnegative")
  if(!isTRUE(all.equal(current = sum(x), target = 1.0)))
  {
    stop("The elements in a probability mass function must sum up to 1")
  } # IF
}

#' Void internal function to check a supplied correlation coefficient
#'
#' A correlation coefficient must be a numeric scalar in [-1, 1]
#'
#' @param x Correlation coefficient
#' @author Max Welz
#' @noRd
.input_check_rho <- function(x)
{
  if(!is.numeric(x) || !is.vector(x) || length(x) > 1L)
  {
    stop("Correlation coefficients must be a numeric vector of length 1")
  } # IF

  if(!(-1.0 <= x && x <= 1.0))
  {
    stop("Correlation coefficients must take values in [-1, 1]")
  } # IF
}

