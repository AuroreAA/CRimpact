#' Cronbach alpha under our assumptions
#'
#' @param J construct size
#' @param rho Within-construct correlation between items in a construct comprising items that are each identically distributed
#'
#' @return Cronbach alpha (numeric scalar)
#' @author Max Welz
#' @export
cronbach <- function(J, rho)
{
  ## input checks
  .input_check_constructsize(J)
  .input_check_rho(rho)

  ## call main function
  .cronbach(J = J, rho = rho)
}


#' Internal function to calculate cronbach alpha
#'
#'
#' @author Max Welz
#' @noRd
.cronbach <- function(J, rho)
{
  J / (J-1) * (1 - 1 / (1 + (J-1) * rho))
}

#' Calculate bias at a given contaminating distribution
#'
#' @param piFX A probability mass function (PMF) under the model distribution of a rating-scale variable \code{X}. The \eqn{k}-th element of a PMF corresponds to the probability that the \eqn{k}-th response category is chosen, for all elements \eqn{k = 1,2,\dots} of the PMF.
#' @param piFY Same as \code{piFX}, just for another rating-scale variable \code{Y}
#' @param piHX Same as \code{piFX}, just under a contaminating distribution
#' @param piHY Same as \code{piFY}, just under a contaminating distribution
#' @param rhoX Within-construct correlation between items in a construct comprising items that are each distributed according to \code{piFX}
#' @param rhoY Within-construct correlation between items in a construct comprising items that are each distributed according to \code{piFY}
#' @param rhoXY Correlation between sum-scores \eqn{X = \sum_{j=1}^J X_j} and \eqn{Y = \sum_{j=1}^J Y_j} under model distribution
#' @param phiX Same as \code{rhoX}, just under the contaminating distribution
#' @param phiY Same as \code{rhoY}, just under the contaminating distribution
#' @param phiXY Same as \code{rhoXY}, just under the contaminating distribution
#' @param JX Size of the X-scale
#' @param JY Size of the Y-scale
#' @param eps Contamination fractions: Numeric vector whose elements are in [0,1]
#'
#' @return Values of the bias
#'
#' @author Max Welz
#'
#' @export
bias <- function(eps, JX, JY = JX,
                 piFX, rhoXY, rhoX,
                 piHX, phiXY, phiX,
                 piFY = piFX, rhoY = rhoX,
                 piHY = piHX, phiY = phiX)
{
  ## input checks
  .input_check_pmf(piFX)
  .input_check_pmf(piFY)
  .input_check_pmf(piHX)
  .input_check_pmf(piHY)
  .input_check_rho(rhoX)
  .input_check_rho(rhoY)
  .input_check_rho(rhoXY)
  .input_check_rho(phiX)
  .input_check_rho(phiY)
  .input_check_rho(phiXY)
  .input_check_constructsize(JY)
  .input_check_constructsize(JX)
  .input_check_contamfrac(eps)
  .input_check_equallength(piFX, piHX)
  .input_check_equallength(piFY, piHY)

  ## get support regions in right form
  supportX_ls <- .get_support(piFX)
  supportY_ls <- .get_support(piFY)

  ## call main function
  .bias(piX = piFX, piY = piFY,
        piHX = piHX, piHY = piHY,
        supportX = supportX_ls$support,
        supportY = supportY_ls$support,
        rhoX = rhoX,
        rhoY = rhoY,
        rhoXY = rhoXY,
        phiX = phiX,
        phiY = phiY,
        phiXY = phiXY,
        JX = JX,
        JY = JY,
        eps = eps,
        MX = supportX_ls$M,
        MY = supportY_ls$M)
} # FUN


#' Internal function to calculate bias curve at given contaminating distribution. Support regions are of form {-M,...,M}
#' @author Max Welz
#' @noRd
.bias <- function(piX, piY, piHX, piHY,
                  supportX, supportY,
                  rhoX, rhoY, rhoXY,
                  phiX, phiY, phiXY,
                  JX, JY, eps, MX, MY)
{
  # useful variables
  meps  <- 1.0 - eps
  meps2 <- meps^2

  #### model distribution F
  # moments
  mntsX <- .moments(piX, support = supportX)
  mntsY <- .moments(piY, support = supportY)

  # marginal variances and means
  varX <- unname(mntsX["variance"])
  varY <- unname(mntsY["variance"])
  muX <- unname(mntsX["moment1"])
  muY <- unname(mntsY["moment1"])
  muX2 <- muX^2
  muY2 <- muY^2
  muXmuY <- muX * muY
  VX <- varX * (1.0 + (JX - 1.0) * rhoX) / JX
  VY <- varY * (1.0 + (JY - 1.0) * rhoY) / JY

  # m-functions
  mXY <- meps * (rhoXY * sqrt(VX * VY) + muXmuY) - meps2 * muXmuY
  mX  <- meps * (VX + muX2) - meps2 * muX2
  mY  <- meps * (VY + muY2) - meps2 * muY2


  ## contaminating distribution H
  # moments under H
  mntsHX <- .moments(piHX, support = supportX)
  mntsHY <- .moments(piHY, support = supportY)

  # marginal variances and means
  tau2X <- unname(mntsHX["variance"])
  tau2Y <- unname(mntsHY["variance"])
  nuX <- unname(mntsHX["moment1"])
  nuY <- unname(mntsHY["moment1"])
  WX <- tau2X * (1.0 + (JX - 1.0) * phiX) / JX
  WY <- tau2Y * (1.0 + (JY - 1.0) * phiY) / JY

  # final terms
  covG <- mXY +
    eps * (meps * (nuX*nuY - muX*nuY - muY*nuX) +
             phiXY * sqrt(WX * WY))

  varGX <- mX + eps * (meps * nuX * (nuX - 2 * muX) + WX )
  varGY <- mY + eps * (meps * nuY * (nuY - 2 * muY) + WY )

  return(covG / sqrt(varGX * varGY) - rhoXY)

}


#' Calculate maximum upward bias and maximum downward bias
#'
#' @param piX A probability mass function (PMF) of a rating-scale variable \code{X}. The \eqn{k}-th element of a PMF corresponds to the probability that the \eqn{k}-th response category is chosen, for all elements \eqn{k = 1,2,\dots} of the PMF.
#' @param piY Same as \code{piX}, just for another rating-scale variable \code{Y}. By default equal to \code{piX}.
#' @param rhoX Within-construct correlation between items in a construct comprising items that are each distributed according to \code{piX}
#' @param rhoY Within-construct correlation between items in a construct comprising items that are each distributed according to \code{piX}. By default equal to \code{rhoY}.
#' @param rhoXY Correlation between sum-scores \eqn{X = \sum_{j=1}^J X_j} and \eqn{Y = \sum_{j=1}^J Y_j}
#' @param JX Size of the X-scale
#' @param JY Size of the Y-scale
#' @param eps Contamination fractions: Numeric vector whose elements are in [0,1]
#'
#' @return  A list comprising maximum upward bias and maximum downward bias
#'
#' @export
#' @author Max Welz
maxbias <- function(eps, JX, JY = JX,
                    piX, rhoXY, rhoX,
                    piY = piX, rhoY = rhoX)
{
  ## input checks
  .input_check_pmf(piX)
  .input_check_pmf(piY)
  .input_check_rho(rhoX)
  .input_check_rho(rhoY)
  .input_check_rho(rhoXY)
  .input_check_constructsize(JX)
  .input_check_constructsize(JY)
  .input_check_contamfrac(eps)

  ## get support regions in right form
  supportX_ls <- .get_support(piX)
  supportY_ls <- .get_support(piY)

  ## call main function
  .maxbias(piX = piX, piY = piY,
           supportX = supportX_ls$support,
           supportY = supportY_ls$support,
           rhoX = rhoX,
           rhoY = rhoY,
           rhoXY = rhoXY,
           JX = JX,
           JY = JY,
           eps = eps,
           MX = supportX_ls$M,
           MY = supportY_ls$M)
} # FUN


#' Internal function to calculate maximum bias curves. Support regions are of form {-M,...,M}
#'
#' @author Max Welz
#' @noRd
.maxbias <- function(piX, piY, supportX, supportY, rhoX, rhoY, rhoXY, JX, JY, eps, MX, MY)
{
  # useful variables
  meps  <- 1.0 - eps
  meps2 <- meps^2
  MXMY  <- MX * MY

  # moments
  mntsX <- .moments(piX, support = supportX)
  mntsY <- .moments(piY, support = supportY)

  # marginal variances and means
  varX <- unname(mntsX["variance"])
  varY <- unname(mntsY["variance"])
  muX <- unname(mntsX["moment1"])
  muY <- unname(mntsY["moment1"])
  muX2 <- muX^2
  muY2 <- muY^2
  muXmuY <- muX * muY
  VX <- varX * (1.0 + (JX - 1.0) * rhoX) / JX
  VY <- varY * (1.0 + (JY - 1.0) * rhoY) / JY

  # m-functions
  mXY <- meps * (rhoXY * sqrt(VX * VY) + muXmuY) - meps2 * muXmuY
  mX  <- meps * (VX + muX2) - meps2 * muX2
  mY  <- meps * (VY + muY2) - meps2 * muY2

  # numerator and denominator
  num_up <- mXY + eps * MXMY
  num_dw <- mXY - eps * MXMY
  denom <- sqrt(mX + eps * MX^2) * sqrt(mY + eps * MY^2)

  # maximum upward and downward bias
  Bplus  <- num_up / denom - rhoXY
  Bminus <- num_dw / denom - rhoXY

  return(list(Bplus = Bplus,
              Bminus = Bminus))
}


#' Visualize bias curves at specific contaminating distribution
#'
#' @param FX Either a probability mass function (PMF) of a rating-scale variable \code{X} or a character in \code{c("centered", "agreed", "polarized")}. The \eqn{k}-th element of a PMF corresponds to the probability that the \eqn{k}-th response category is chosen, for all elements \eqn{k = 1,2,\dots} of the PMF.
#' @param HX Character denoting the type of contaminating distribution for the \code{X}-scale. Must be in  \code{c("random", "straightlining", "extreme")}
#' @param rhoXY Correlation between scores \eqn{X = \sum_{j=1}^J X_j / J_X} and \eqn{Y = \sum_{j=1}^J Y_j / J_Y} under model distribution \code{F}
#' @param rhoscaleX Within-scale correlation between items in the X-scale comprising items that are each distributed according to model distribution \code{F}
#' @param JX Size of the X-scale
#' @param FY Same as \code{FX}, just for another rating-scale variable \code{Y}
#' @param HY Same as \code{HX}, just for the \code{Y}-construct
#' @param rhoscaleY Same as \code{rhoscaleX}, just for Y-scale
#' @param JY Size of the Y-scale
#' @param KX Number of Likert-type response categories for the items corresponding to \code{X}. Only needs to be specified if \code{FX} is a character
#' @param KY Same as \code{KX}, just for another construct \code{Y}
#' @param straightatX Index of answer category which is straightline for \code{X}-items (default is 1). Only applicable when \code{HX = "straight"}
#' @param straightatY Same as \code{straightatX}, just for \code{Y}-items
#' @param eps Contamination fractions that shall be plotted
#' @param digits Number of digits shown in the hover.
#'
#' @return A \code{ggplot} object
#' @export
#' @seealso [bias()],  [get_contam_distribution()]
#' @importFrom scales percent
#' @author Aurore Archimbaud and Max Welz
#' @rawNamespace import(ggplot2, except = last_plot)
bias_plot <- function (FX, HX, rhoXY, rhoscaleX, JX, FY = FX, HY = HX, rhoscaleY = rhoscaleX,
                       JY = JX, KX = NULL, KY = KX, straightatX = 1, straightatY = 1,
                       eps = seq(from = 0, to = 0.5, by = 0.01),
                       digits = 2)
{
  piX <- piY <- piHX <- piHY <- numeric()
  isnullKX <- is.null(KX)
  isnullKY <- is.null(KY)
  if (is.character(FX)) {
    if (isnullKX) {
      stop("When 'FX' is a character, you must provide the number of answer categories KX")
    }
    else {
      piX <- get_model_distribution(type = FX, K = KX)
    }
  }
  else {
    .input_check_pmf(x = FX)
    piX <- FX
  }
  kx <- length(piX)
  if (is.character(FY)) {
    if (is.null(KY)) {
      KY <- kx
      message("No value for KY was passed, so set it equal to KX")
    }
    piY <- get_model_distribution(type = FY, K = KY)
  }
  else {
    .input_check_pmf(x = FY)
    piY <- FY
  }
  ky <- length(piY)
  if (is.character(HX)) {
    piHX <- get_contam_distribution(type = HX, K = kx, straightat = straightatX)
  }
  else {
    stop("HX must be a character vector equaling an element in c(\"random\", \"straightlining\", \"extreme\")")
  }
  if (is.character(HY)) {
    piHY <- get_contam_distribution(type = HY, K = ky, straightat = straightatY)
  }
  else {
    stop("HY must be a character vector equaling an element in c(\"random\", \"straightlining\", \"extreme\")")
  }
  phiXY <- 0
  phiscale <- phiXY
  BS <- bias(eps = eps, JX = JX, JY = JY, piFX = piX, piFY = piY,
             piHX = piHX, piHY = piHY, rhoXY = rhoXY, phiXY = phiXY,
             rhoX = rhoscaleX, rhoY = rhoscaleY, phiX = phiscale,
             phiY = phiscale)
  if(!is.null(digits)){
    BS <- round(BS, digits)
  }

  gg <- ggplot(data = data.frame(bias = BS, contamination = eps), aes(y = bias, x = contamination, text = paste0(
    "Contamination: ", scales::percent(contamination, accuracy = 1),
    "<br>",
    "Bias: ", bias
  ),  group = 1)) +
    geom_line()+
    scale_x_continuous(labels = scales::percent)+
    ylim(-2, 2) +
    xlab("Contamination fraction") + ylab("Bias")
  return(gg)
}

