#' Internal function to get support region in form {-M, ..., M} by deducting the central answer category
#'
#' @param x A probability mass function (PMF) of a rating-scale variable. The \eqn{k}-th element of a PMF corresponds to the probability that the \eqn{k}-th response category is chosen, for all elements \eqn{k} of the PMF.
#'
#' @return list containing rescaled support region (\code{support}) and its maximum value (\code{M})
#'
#' @author Max Welz
#' @noRd
.get_support <- function(x)
{
  ## rescale support
  support_tmp <- seq_along(x)
  support <- support_tmp - stats::median(support_tmp)

  ## get M = max(support)
  M <- support[length(x)]

  return(list(support = support, M = M))
}

#' internal function to calculate moments of a rating-scale variable
#'
#' Calculates first two moments and variance
#'
#' @param x PMF of a rating-scale variable
#' @param support support region of the variable. Must be of form \eqn{\{-M,\dots, M\}}.
#'
#' @return A numeric vector of the first two moments and variance implied by the supplied PMF
#'
#' @author Max Welz
#' @noRd
.moments <- function(pi, support)
{

  ## calculate moments based on support
  m1 <- sum(support * pi)   # 1st moment
  m2 <- sum(support^2 * pi) # 2st moment
  var. <- m2 - m1^2         # variance

  return(c(moment1 = m1, moment2 = m2, variance = var.))
}
